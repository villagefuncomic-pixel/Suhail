export const VEHICLE_MAP: Record<VehicleId, VehicleSpec> = Object.fromEntries(
  VEHICLES.map((v) => [v.id, v]),
) as Record<VehicleId, VehicleSpec>;

export function createDefaultTuning(vehicleId: VehicleId): TuningConfig {
  const spec = VEHICLE_MAP[vehicleId];
  const isF1 = spec.category === 'f1';
  const defaultRim =
    vehicleId === 'suhailll' || vehicleId === 'rolex_f1' || vehicleId === 'ducati_v4_corsa'
      ? 'forged_gold'
      : isF1
      ? 'gloss_black'
      : 'titanium';

  return {
    paintColor: spec.defaultPaint,
    paintFinish: vehicleId === 'redbull_f1' ? 'matte' : 'metallic',
    rimFinish: defaultRim,
    underglow: vehicleId === 'suhailll',
    underglowColor: vehicleId === 'suhailll' ? '#f59e0b' : '#06b6d4',
    ecuStage: isF1 || vehicleId === 'suhailll' ? 2 : 1,
    gearRatioBias: vehicleId === 'suhailll' ? 62 : 50,
    suspensionHeight: 0,
    suspensionStiffness: isF1 ? 92 : 65,
    aeroDownforce: isF1 ? 85 : 60,
    brakeBias: 58,
    tireCompound: isF1
      ? 'soft_f1'
      : spec.category === 'xuv'
      ? 'all_terrain'
      : 'semi_slick',
  };
}

export function computeTunedStats(
  spec: VehicleSpec,
  tuning: TuningConfig,
): ComputedVehicleStats {
  const stagePowerMult = [1.0, 1.1, 1.22, 1.36][tuning.ecuStage] ?? 1.0;
  const stageRpmBonus = [0, 300, 600, 950][tuning.ecuStage] ?? 0;
  const stageWeightDelta = [0, -15, -35, -55][tuning.ecuStage] ?? 0;

  const hp = Math.round(spec.baseHp * stagePowerMult);
  const weightKg = Math.max(150, spec.baseWeightKg + stageWeightDelta);

  const gearNorm = (tuning.gearRatioBias - 50) / 50; // -1 .. +1
  const aeroNorm = tuning.aeroDownforce / 100; // 0 .. 1

  const compoundGripMap: Record<TuningConfig['tireCompound'], number> = {
    soft_f1: 1.24,
    medium_f1: 1.15,
    hard_f1: 1.08,
    street: 1.0,
    semi_slick: 1.16,
    drift: 0.84,
    all_terrain: 1.06,
  };
  const compoundDriftMap: Record<TuningConfig['tireCompound'], number> = {
    soft_f1: 0.65,
    medium_f1: 0.72,
    hard_f1: 0.8,
    street: 1.0,
    semi_slick: 0.78,
    drift: 1.55,
    all_terrain: 1.1,
  };

  const tireGripMult = compoundGripMap[tuning.tireCompound] ?? 1.0;
  const driftSlipFactor = compoundDriftMap[tuning.tireCompound] ?? 1.0;

  const topSpeedKmh = Math.round(
    spec.baseTopSpeedKmh *
      (1 + (stagePowerMult - 1) * 0.28 + gearNorm * 0.08 - aeroNorm * 0.035),
  );

  const accelRatio =
    stagePowerMult * (1 - gearNorm * 0.12) * (spec.baseWeightKg / weightKg);
  const zeroToHundredSec = Number(
    Math.max(1.45, spec.baseZeroToHundred / Math.pow(accelRatio, 0.55)).toFixed(2),
  );

  const heightPenalty = Math.max(0, tuning.suspensionHeight) * 0.008;
  const stiffBonus = (tuning.suspensionStiffness / 100) * 0.08;
  const lateralGrip =
    spec.baseGrip * tireGripMult * (1 + aeroNorm * 0.16 + stiffBonus - heightPenalty);

  const gripRating = Math.min(100, Math.round(lateralGrip * 56));
  const brakingRating = Math.min(
    100,
    Math.round(
      74 +
        (tireGripMult - 1) * 60 +
        aeroNorm * 10 -
        Math.abs(tuning.brakeBias - 58) * 0.3,
    ),
  );
  const handlingScore = Math.min(
    100,
    Math.round(
      gripRating * 0.55 + brakingRating * 0.3 + tuning.suspensionStiffness * 0.15,
    ),
  );

  return {
    hp,
    weightKg,
    topSpeedKmh,
    zeroToHundredSec,
    gripRating,
    brakingRating,
    handlingScore,
    accelerationForce:
      15.8 * (hp / Math.max(380, weightKg * 0.76)) * (1 - gearNorm * 0.14),
    lateralGrip,
    downforceFactor: 0.4 + aeroNorm * 0.9,
    dragFactor: spec.dragCoeff * (0.92 + aeroNorm * 0.2),
    gearScale: 1 + gearNorm * 0.15,
    rideHeightOffset: tuning.suspensionHeight * 0.007,
    suspensionSpring: 0.4 + (tuning.suspensionStiffness / 100) * 0.6,
    maxRpm: spec.maxRpm + stageRpmBonus,
    driftSlipFactor,
  };
}

